-- =====================================================================
-- P4-DB1：记录文档入库时使用的向量模型（用于检测「向量已过期」）
-- =====================================================================
-- 背景（P4 功能1 遗留问题）：
--     embedding 在 QWEN_API_KEY 未配置时会走 mock 向量（确定性伪向量，无语义）。
--     若某文档在「Key 尚未配置」时入库，它的向量就不具备语义相似度，
--     之后即使配好 Key，检索也会把它召回到无关问题上——表现为「检索能用但答案跑偏」。
--     同理，更换 embedding 模型后，新旧向量处在不同语义空间，混检同样无效。
--
-- 解法：
--     在 documents 上记录入库时实际使用的向量模型签名：
--       - 真实模型：写入模型名（如 qwen3.7-text-embedding-flash）
--       - mock 模式：写入 "mock"
--     接口层把它与「当前配置」比对，不一致就在文档列表提示「向量已过期，建议重新入库」。
--
-- 说明：
--   - 历史数据该列为 NULL（无法追溯当时用了什么），接口层按「需重新入库」处理，
--     重新入库一次即自动回填；
--   - 仅新增可空列，不影响既有读写路径，幂等可重复执行。
-- =====================================================================

ALTER TABLE documents ADD COLUMN IF NOT EXISTS embedding_model VARCHAR(64);

COMMENT ON COLUMN documents.embedding_model IS
    '入库时使用的向量模型签名：模型名（真实）或 mock（未配置 Key 时的伪向量）；NULL=历史数据未记录，P4 检索建议重新入库';
